def 본문만(md: str) -> tuple[str, list[tuple[int, str]]]:
    """코드블록·표·헤딩·해시태그를 뺀 산문만 돌려준다. (줄번호, 줄) 목록도 같이."""
    줄들 = md.split("\n")
    안쪽 = False
    남김: list[tuple[int, str]] = []
    for n, line in enumerate(줄들, 1):
        if line.strip().startswith("```"):
            안쪽 = not 안쪽
            continue
        if 안쪽:
            continue
        s = line.strip()
        if not s or s.startswith(("|", "#", "\\#", ">")):
            continue
        남김.append((n, line))
    return "\n".join(l for _, l in 남김), 남김


def 검사(path: Path) -> int:
    md = path.read_text(encoding="utf-8")
    산문, 줄목록 = 본문만(md)
    글자 = len(산문)
    기준 = max(1, 글자 / 4000)          # 4천 자를 1로 보고 한도를 비례시킨다

    print(f"\n{'=' * 72}")
    print(f"{path.name}")
    print(f"산문 {글자:,}자 · 문단 {len(줄목록)}개")
    print("=" * 72)

    걸림 = 0
    for id_, 이름, 패턴, 한도, 설명 in 규칙:
        if 패턴 is None:
            continue
        flags = re.M if 패턴.startswith("^") else 0
        찾음 = [(n, l) for n, l in 줄목록 if re.search(패턴, l.strip(), flags)]
        건수 = sum(len(re.findall(패턴, l.strip(), flags)) for _, l in 줄목록)
        허용 = round(한도 * 기준) if 한도 else 한도
        if 건수 <= 허용:
            continue
        걸림 += 1
        print(f"\n  [{id_}] {이름}  {건수}건 (한도 {허용})")
        print(f"        {설명}")
        for n, l in 찾음[:3]:
            m = re.search(패턴, l.strip(), flags)
            조각 = l.strip()
            자리 = max(0, m.start() - 18)
            print(f"        {n:>4}줄  …{조각[자리:자리 + 56]}…")
        if len(찾음) > 3:
            print(f"        … 그 밖 {len(찾음) - 3}줄")

    # 쉼표 포함률 (C-12)
    문장 = [s for s in re.split(r"(?<=[.!?])\s+", 산문) if len(s) > 10]
    if 문장:
        비율 = sum(1 for s in 문장 if "," in s) / len(문장)
        if 비율 > 0.5:
            걸림 += 1
            print(f"\n  [C-12] 쉼표 과다  {비율:.0%} 문장에 쉼표 (한도 50%)")
            print("        일부는 마침표로 나눈다")

    # 종결어미 쏠림 (E-2)
    끝 = Counter(m.group(1)[-4:] for m in re.finditer(r"([가-힣]{2,6})\.(?:\s|$)", 산문))
    if 끝:
        흔한, 수 = 끝.most_common(1)[0]
        쏠림 = 수 / sum(끝.values())
        if 쏠림 > 0.25:
            걸림 += 1
            print(f"\n  [E-2] 종결어미 쏠림  「{흔한}」이 {쏠림:.0%}")
            print("        어미를 흩는다")

    print(f"\n  걸린 항목 {걸림}개" if 걸림 else "\n  걸린 것 없음")
    return 걸림


